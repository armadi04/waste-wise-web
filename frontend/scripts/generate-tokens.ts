/**
 * Generate `src/styles/tokens.css` from the palette source of truth.
 *
 * Run: bun run tokens:generate
 */
import { writeFileSync } from 'node:fs'
import { appTokens } from '../src/lib/theme/palette'
import type { ThemeName } from '../src/lib/theme/palette'

const HEADER = `/* Generated by scripts/generate-tokens.ts from src/lib/theme/palette.ts. Do not edit directly. */`

const renderTheme = (theme: ThemeName) => {
  const entries = Object.entries(appTokens[theme])
  const declarations = entries
    .map(([token, value]) => `  --app-${token}: ${value};`)
    .join('\n')

  return `:root.${theme} {\n  color-scheme: ${theme};\n${declarations}\n}`
}

const css = [HEADER, renderTheme('light'), renderTheme('dark')].join('\n\n')

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), `${css}\n`)
